#!/bin/bash
# this file has been modified with the assistance of AI Tool [claude 4.6]
# Assemble an omnibus-shaped artifact tarball for s390x by hand.
#
# This replaces the omnibus pipeline (Option 1 of
# docs/datadog-agent-s390x-container-image-gap-analysis.md). The upstream
# Dockerfile does not care how the tarball is produced -- it globs for
# datadog-agent*-$TARGETARCH.tar.xz and untars it at / -- so we lay out the
# same directory structure omnibus would emit and tar it.
#
# Usage: make-artifact.sh <bin-dir> <agent-src-dir> <output-dir>
set -euo pipefail

BIN="${1:?usage: make-artifact.sh <bin-dir> <agent-src-dir> <output-dir>}"
SRC="${2:?}"
OUTDIR="${3:?}"
VERSION=7.79.2
ARCH=s390x

for b in agent trace-agent process-agent; do
    [ -f "$BIN/$b" ] || { echo "FATAL: $BIN/$b missing"; exit 2; }
done

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

# --- the layout omnibus produces -------------------------------------------
# (see omnibus/config/software/datadog-agent.rb and datadog-agent-finalize.rb)
mkdir -p "$STAGE/opt/datadog-agent/bin/agent"
mkdir -p "$STAGE/opt/datadog-agent/embedded/bin"
mkdir -p "$STAGE/opt/datadog-agent/embedded/ssl/certs"
mkdir -p "$STAGE/opt/datadog-agent/embedded/share/system-probe/ebpf/co-re"
mkdir -p "$STAGE/opt/datadog-agent/run"
mkdir -p "$STAGE/etc/datadog-agent/conf.d"
mkdir -p "$STAGE/etc/datadog-agent/checks.d"
mkdir -p "$STAGE/var/log/datadog"

# main agent + its dist tree (core check configs, assets)
install -m 0755 "$BIN/agent" "$STAGE/opt/datadog-agent/bin/agent/agent"
cp -a "$SRC/cmd/agent/dist" "$STAGE/opt/datadog-agent/bin/agent/dist"

# sidecar binaries live under embedded/bin, same as omnibus
install -m 0755 "$BIN/trace-agent"   "$STAGE/opt/datadog-agent/embedded/bin/trace-agent"
install -m 0755 "$BIN/process-agent" "$STAGE/opt/datadog-agent/embedded/bin/process-agent"

# trace-loader: the s6 `trace` service execs it to launch trace-agent. For
# non-FIPS builds omnibus just installs the no-op shim
# (omnibus/config/software/datadog-agent.rb:155), so do the same.
install -m 0755 "$SRC/cmd/loader/main_noop.sh" \
    "$STAGE/opt/datadog-agent/embedded/bin/trace-loader"

# Config. omnibus ships a datadog.yaml.example; the Dockerfile's extract stage
# then overlays the container-specific datadog-{docker,ecs,kubernetes,ci}.yaml
# from its build context, and cont-init.d/51-docker.sh symlinks one of those to
# datadog.yaml at container start. So the .example is informational only.
#
# Source it from pkg/config/config_template.yaml, which is tracked in git.
# cmd/agent/dist/datadog.yaml is NOT tracked -- it is generated by
# `dda inv agent.build` -- so relying on it breaks on a clean source tree.
if [ -f "$SRC/pkg/config/config_template.yaml" ]; then
    cp "$SRC/pkg/config/config_template.yaml" "$STAGE/etc/datadog-agent/datadog.yaml.example"
elif [ -f "$SRC/cmd/agent/dist/datadog.yaml" ]; then
    cp "$SRC/cmd/agent/dist/datadog.yaml" "$STAGE/etc/datadog-agent/datadog.yaml.example"
else
    echo "WARN: no config template found; shipping no datadog.yaml.example" >&2
fi
if [ -d "$SRC/cmd/agent/dist/conf.d" ]; then
    cp -a "$SRC/cmd/agent/dist/conf.d/." "$STAGE/etc/datadog-agent/conf.d/"
fi

# omnibus marks the install root; package scripts and the agent look for it
touch "$STAGE/opt/datadog-agent/.install_root"

# version manifest (omnibus generates a full one from its software defs; ours
# records what this hand-rolled build actually contains)
cat > "$STAGE/opt/datadog-agent/version-manifest.txt" <<MANIFEST
datadog-agent $VERSION

Component          Version
------------------ ----------------
agent              $VERSION
trace-agent        $VERSION
process-agent      $VERSION
go                 1.26.3
build              hand-assembled (no omnibus), $ARCH
MANIFEST

mkdir -p "$OUTDIR"
TARBALL="$OUTDIR/datadog-agent-$VERSION-1-$ARCH.tar.xz"
rm -f "$TARBALL"
tar -C "$STAGE" -cJf "$TARBALL" .

echo "wrote $TARBALL"
# NB: do not pipe tar into head -- under `set -o pipefail` the SIGPIPE'd tar
# returns 141 and aborts the script (and any caller running under `set -e`).
LISTING="$STAGE/.listing"
tar -tJf "$TARBALL" > "$LISTING"
head -12 "$LISTING"
echo "... $(wc -l < "$LISTING") entries total"
du -h "$TARBALL"
